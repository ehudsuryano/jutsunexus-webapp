/** Arrows that point along the reading direction; mirrored in right-to-left pages. */
const DIRECTIONAL = new Set(['back', 'prev', 'next', 'arrow']);

export function icon(name, size = 24) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', size);
  svg.setAttribute('height', size);
  svg.setAttribute('aria-hidden', 'true');
  if (DIRECTIONAL.has(name)) svg.setAttribute('class', 'flip-rtl');
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('fill', 'currentColor');
  path.setAttribute('d', ICONS[name] || ICONS.doc);
  svg.append(path);
  return svg;
}

export function iconButton(name, label, onclick, extraClass = '') {
  return h('button', { class: `icon-btn ${extraClass}`, type: 'button', 'aria-label': label, title: label, onclick },
    icon(name));
}

