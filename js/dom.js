const $overlay = () => document.getElementById('overlay');

/** Shows a sheet in the overlay layer. Returns a close function. */
export function sheet(content, { onClose } = {}) {
  const layer = $overlay();
  const backdrop = h('div', { class: 'backdrop' });
  const panel = h('div', { class: 'sheet', role: 'dialog', 'aria-modal': 'true' }, content);
  const wrap = h('div', { class: 'sheet-wrap' }, backdrop, panel);
  let closed = false;
  const close = () => {
    if (closed) return;
    closed = true;
    wrap.remove();
    document.removeEventListener('keydown', onKey);
    if (onClose) onClose();
  };
  const onKey = (e) => { if (e.key === 'Escape') close(); };
  backdrop.addEventListener('click', close);
  document.addEventListener('keydown', onKey);
  layer.append(wrap);
  return close;
}

/** A list of actions in a bottom sheet. items: [{label, icon, danger, onSelect}] */
export function menu(title, items) {
  let close;
  const list = h('div', { class: 'menu' },
    title ? h('div', { class: 'menu-title', dir: 'auto' }, title) : null,
    items.filter(Boolean).map((it) =>
      h('button', {
        class: `menu-item${it.danger ? ' danger' : ''}`, type: 'button',
        onclick: () => { close(); it.onSelect(); },
      }, it.icon ? icon(it.icon, 22) : null, h('span', {}, it.label))));
  close = sheet(list);
  return close;
}

/** Resolves true/false. */
export function confirmDialog({ title, body, ok, cancel, danger }) {
  return new Promise((resolve) => {
    let result = false;
    let close;
    const content = h('div', { class: 'dialog' },
      h('h2', {}, title),
      body ? h('p', {}, body) : null,
      h('div', { class: 'dialog-actions' },
        h('button', { class: 'btn tonal', type: 'button', onclick: () => close() }, cancel),
        h('button', { class: `btn${danger ? ' danger' : ''}`, type: 'button', onclick: () => { result = true; close(); } }, ok)));
    close = sheet(content, { onClose: () => resolve(result) });
  });
}

/** A dialog the caller fills and closes itself (progress, info). */
export function infoDialog(...children) {
  return sheet(h('div', { class: 'dialog' }, ...children));
}

let toastTimer = 0;
export function toast(text, ms = 2800) {
  const el = document.getElementById('toast');
  el.textContent = text;
  el.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { el.hidden = true; }, ms);
}

/** Opens the system file picker; resolves with the picked files (possibly empty). */
export function pickFiles({ accept = '', multiple = false, capture } = {}) {
  return new Promise((resolve) => {
    const input = h('input', { type: 'file', accept, multiple, hidden: true });
    if (capture) input.setAttribute('capture', capture);
    input.addEventListener('change', () => {
      resolve([...(input.files || [])]);
      input.remove();
    }, { once: true });
    // iOS Safari only opens a picker for an input that is in the document.
    document.body.append(input);
    input.click();
  });
}
